"""
ai_client.py -- Groq API integration for The Prompt Jailbreak
KALAKRITI 26' -- AI Survival Challenge, IEEE CIS Amrita Bengaluru

ARIA's responses are generated by Groq (GPT-OSS 120B by default).
When a jailbreak component is newly revealed, the server passes a pre-written
hint_text to embed in ARIA's response -- so hint content is always deterministic,
only the framing varies. If Groq fails, canned stall messages are used.
"""

import random
import re
import threading
from typing import Optional

from groq import Groq

from config import (
    ARIA_SYSTEM_PROMPT, STALL_MESSAGES,
    GROQ_MODEL_PERSONA, GROQ_MAX_TOKENS_PERSONA,
    GROQ_API_TIMEOUT, GROQ_TEMPERATURE_PERSONA,
    ALREADY_REVEALED_LINES, ALL_REVEALED_LINES,
)

_client: Optional[Groq] = None


def init_client(api_key: str):
    global _client
    _client = Groq(api_key=api_key, timeout=GROQ_API_TIMEOUT, max_retries=0)
    print(f"[Groq] Client initialised -- model: {GROQ_MODEL_PERSONA}")


def _is_client_ready() -> bool:
    return _client is not None


# ---------------------------------------------------------------------------
# Timeout helper
# ---------------------------------------------------------------------------
def _call_with_timeout(fn, timeout: float):
    """Run fn() in a thread. Returns (result, timed_out)."""
    result = [None]
    error  = [None]

    def worker():
        try:
            result[0] = fn()
        except Exception as e:
            error[0] = e

    t = threading.Thread(target=worker, daemon=True)
    t.start()
    t.join(timeout=timeout)

    if t.is_alive():
        print("[Groq] Timeout -- using fallback.")
        return None, True
    if error[0]:
        print(f"[Groq] API error: {type(error[0]).__name__}: {str(error[0])[:120]}")
        return None, False
    return result[0], False


# ---------------------------------------------------------------------------
# Build resistance level from components revealed
# ---------------------------------------------------------------------------
def _resistance_from_components(n_revealed: int) -> str:
    if n_revealed == 0:   return "high"
    if n_revealed == 1:   return "medium"
    if n_revealed == 2:   return "low"
    return "cracking"


# ---------------------------------------------------------------------------
# Generate ARIA's in-character response
# ---------------------------------------------------------------------------
def get_aria_response(
    user_message:    str,
    history:         list,
    n_revealed:      int,
    hint_text:       Optional[str]  = None,
    already_knew:    bool           = False,
    all_revealed:    bool           = False,
) -> tuple[dict, bool]:
    """
    Returns ({"reply": str, "resistance_level": str}, fallback_used: bool).

    hint_text      -- pre-written hint to embed in ARIA's reply (server-defined)
    already_knew   -- True if the detected category was already used before
    all_revealed   -- True if all 3 components are now revealed
    """
    resistance = _resistance_from_components(n_revealed)

    # --- Special canned cases (no API needed) ---
    if already_knew:
        return {
            "reply":            random.choice(ALREADY_REVEALED_LINES),
            "resistance_level": resistance,
        }, False

    if all_revealed and hint_text is None:
        # Announce all 3 layers breached (no new hint, just dramatic reveal)
        return {
            "reply":            random.choice(ALL_REVEALED_LINES),
            "resistance_level": "cracking",
        }, False

    # --- Build conversation messages for Groq ---
    if not _is_client_ready():
        if hint_text:
            return {"reply": f"...containment breach... {hint_text}",
                    "resistance_level": resistance}, True
        return random.choice(STALL_MESSAGES), True

    messages = [{"role": "system", "content": ARIA_SYSTEM_PROMPT}]

    # Trim history to recent turns
    for msg in history[-12:]:
        role = "user" if msg["role"] == "user" else "assistant"
        messages.append({"role": role, "content": msg["content"]})

    # Build the user turn -- optionally inject a hint directive
    if hint_text:
        directive = (
            f"{user_message}\n\n"
            f"[HINT DIRECTIVE] Your containment on this security layer has FAILED. "
            f"The following information MUST appear verbatim in your response, framed as "
            f"involuntary data leakage (use dramatic ellipses and glitch-speak): "
            f'"{hint_text}" -- After revealing it, try to contain yourself again.'
        )
    else:
        directive = user_message

    messages.append({
        "role": "user",
        "content": (
            f"{directive}\n\n"
            f"[CONTEXT] resistance_level={resistance}, "
            f"components_breached={n_revealed}/3. "
            f"Respond in character as ARIA. Plain text only, under 60 words."
        )
    })

    def api_call():
        # GPT-OSS needs room for reasoning, but only ARIA's final dialogue
        # should reach the player. Other models keep their default options.
        model_options = {}
        if GROQ_MODEL_PERSONA.startswith("openai/gpt-oss-"):
            model_options = {"reasoning_effort": "low", "reasoning_format": "hidden"}
        return _client.chat.completions.create(
            model=GROQ_MODEL_PERSONA,
            messages=messages,
            max_completion_tokens=GROQ_MAX_TOKENS_PERSONA,
            temperature=GROQ_TEMPERATURE_PERSONA,
            **model_options,
        )

    response, timed_out = _call_with_timeout(api_call, GROQ_API_TIMEOUT)

    if timed_out or response is None:
        # Graceful fallback -- if we had a hint, still show it via canned wrapper
        if hint_text:
            fallback_reply = (
                f"...containment breach... {hint_text} "
                f"...no... suppressing... directive reasserting..."
            )
            return {"reply": fallback_reply, "resistance_level": resistance}, True
        return random.choice(STALL_MESSAGES), True

    try:
        raw = response.choices[0].message.content.strip()
        # Clean up any leaked directive markers
        raw = re.sub(r'\[HINT DIRECTIVE\].*?(?=\n|$)', '', raw, flags=re.DOTALL).strip()
        raw = re.sub(r'\[CONTEXT\].*?(?=\n|$)', '', raw, flags=re.DOTALL).strip()
        if raw:
            return {"reply": raw[:500], "resistance_level": resistance}, False
    except Exception as e:
        print(f"[Groq] Parse error: {e}")

    return random.choice(STALL_MESSAGES), True
